const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const acknowledgementsPath = path.join(
  root,
  'ios',
  'Pods',
  'Target Support Files',
  'Pods-BeatNote',
  'Pods-BeatNote-acknowledgements.markdown',
);
const outputPath = path.join(root, 'src', 'data', 'nativeOpenSourceLicences.generated.ts');

if (!fs.existsSync(acknowledgementsPath)) {
  throw new Error(`CocoaPods acknowledgements are missing: ${acknowledgementsPath}`);
}

const markdown = fs.readFileSync(acknowledgementsPath, 'utf8');
const groups = markdown
  .split(/^## /m)
  .slice(1)
  .map(section => {
    const newline = section.indexOf('\n');
    return {
      title: section.slice(0, newline).trim(),
      packages: [section.slice(0, newline).trim()],
      notice: section.slice(newline + 1).trim(),
    };
  })
  .filter(group => group.title.length > 0 && group.notice.length > 0);

if (groups.length === 0) {
  throw new Error('CocoaPods acknowledgements did not contain any licence sections');
}

const source = `// Generated by scripts/generate-native-licences.js from CocoaPods acknowledgements.\n`
  + `// Re-run npm run generate:licences after native dependency changes.\n\n`
  + `import type { OpenSourceLicenceGroup } from './openSourceLicences';\n\n`
  + `export const NATIVE_OPEN_SOURCE_LICENCE_GROUPS: OpenSourceLicenceGroup[] = ${JSON.stringify(groups, null, 2)};\n`;

fs.writeFileSync(outputPath, source);
console.log(`Generated ${groups.length} native licence notices at ${path.relative(root, outputPath)}`);
